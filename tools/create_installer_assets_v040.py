"""Deterministic setup layout using a real native JUCE render, plus original audio.

No plugin artwork is regenerated or painted over. The native screenshot is only
scaled/cropped for the setup's existing branding surfaces.
"""
from pathlib import Path
import wave
import numpy as np
from PIL import Image, ImageDraw, ImageFont

root=Path(__file__).resolve().parents[1]
sr=44100; duration=16; n=sr*duration
audio=np.zeros(n,dtype=np.float64); rng=np.random.default_rng(230)
for beat in range(32):
    start=int(beat*.5*sr); length=min(n-start,int(.45*sr)); u=np.arange(length)/sr
    phase=2*np.pi*(46*u+65*.025*(1-np.exp(-u/.025)))
    audio[start:start+length]+=.6*(np.sin(phase)*np.exp(-u/.13)+rng.normal(0,.12,length)*np.exp(-u/.004))
    at=start+int(.25*sr); m=min(n-at,int(.12*sr)); v=np.arange(m)/sr
    noise=rng.normal(0,1,m); hat=noise-np.concatenate(([0],noise[:-1]))
    audio[at:at+m]+=.06*hat*np.exp(-v/.025)
    freq=[55,55,65.406,55,73.416,55,65.406,49][beat%8]
    at=start+int(.125*sr); m=min(n-at,int(.2*sr)); v=np.arange(m)/sr
    bass=(np.sin(2*np.pi*freq*v)+.25*np.sin(4*np.pi*freq*v))*np.sin(np.pi*np.minimum(v/.012,1)/2)*np.exp(-v/.12)
    audio[at:at+m]+=.22*bass
audio*=.12/np.max(np.abs(audio)); pcm=(np.column_stack([audio,audio])*32767).astype('<i2')
with wave.open(str(root/'installer/OriginalTechno.wav'),'wb') as f:
    f.setnchannels(2); f.setsampwidth(2); f.setframerate(sr); f.writeframes(pcm.tobytes())
(root/'installer/MUSIC.txt').write_text('OriginalTechno.wav: original deterministic synthesized composition for OpenDuck Pro X. No third-party samples or recordings. Peak0.12 (-18.4dBFS); installer only. Audio is optional and does not change device or system volume. Generated by tools/create_installer_assets.py.\n',encoding='utf-8')

preview=root/'build/verification-v0.4.0/Preview/template-100pct.png'
if not preview.exists():
    preview=root/'work/revision040/preview/template-100pct.png'
im=Image.open(preview).convert('RGB')
im.resize((492,260),Image.Resampling.LANCZOS).save(root/'installer/Brand.bmp')
font_path=Path('C:/Windows/Fonts/bahnschrift.ttf')
def font(size):
    return ImageFont.truetype(str(font_path),size) if font_path.exists() else ImageFont.load_default()
card=Image.new('RGB',(344,628),(8,16,22)); d=ImageDraw.Draw(card)
for x in range(344):
    c=int(10+16*(1-x/344)); d.line((x,0,x,627),fill=(c,c+8,c+13))
d.line((24,26,320,26),fill=(0,215,240),width=3)
d.text((26,45),'BLACK CIRCUIT',font=font(21),fill=(164,191,206))

d.text((26,82),'OpenDuck',font=font(43),fill=(235,244,248))
d.text((26,132),'PRO X',font=font(51),fill=(0,225,255))
d.text((28,202),'PRECISION DUCKING',font=font(19),fill=(164,191,206))
thumb=im.copy(); thumb.thumbnail((320,162),Image.Resampling.LANCZOS)
card.paste(thumb,((344-thumb.width)//2,238))
d.text((28,441),'700 PRESET',font=font(28),fill=(235,244,248))
d.text((28,483),'16 SHAPE / AI LOCALE',font=font(20),fill=(145,192,209))
d.line((26,541,318,541),fill=(52,85,99),width=1)
d.text((28,565),'WINDOWS x64  /  VST3',font=font(18),fill=(0,219,246))
d.text((28,592),'VERSIONE 0.4.0',font=font(15),fill=(155,180,192))
card.save(root/'installer/WizardPanel.bmp')
# Small header uses the actual native chrome X, not a newly generated logo.
im.crop((int(im.width*.18),int(im.height*.135),int(im.width*.23),int(im.height*.235))).resize((64,64),Image.Resampling.LANCZOS).save(root/'installer/WizardSmall.bmp')
print('Setup assets exported from the real Premium native render; original audio rebuilt.')
